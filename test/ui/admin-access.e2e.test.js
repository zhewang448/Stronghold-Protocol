import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { startServer } from '../../server/index.js';
import { startAdmin } from '../../server/admin.js';
import { CHROME, hasChrome } from '../e2e/client.mjs';

test('console login and access: desktop/mobile, local reset, remote password and real five-second confirmation', {
  skip: process.env.SP_E2E !== '1' || !hasChrome(), timeout: 60000,
}, async (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-access-ui-'));
  const output = path.resolve('.cache/console-access-ui'); fs.mkdirSync(output, { recursive: true });
  const game = await startServer({ port: 0, host: '127.0.0.1', quiet: true, recovery: false, assetIndex: false });
  const admin = await startAdmin({ lobby: game.lobby, port: 0, resultsDir: dir, settingsFile: path.join(dir, 'settings.json'),
    log: { info() {}, warn() {}, error() {} }, updateOptions: { fetchImpl: async () => new Response('[]') } });
  let browser;
  t.after(async () => { await browser?.close(); await admin.close(); await game.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  browser = await (await import('puppeteer-core')).default.launch({ executablePath: CHROME, headless: true, args: ['--no-sandbox', '--no-first-run', ...(CHROME.toLowerCase().includes('msedge') ? ['--edge-skip-compat-layer-relaunch'] : [])] });
  const page = await browser.newPage(), errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.setViewport({ width: 1440, height: 900 });
  await page.goto(`${admin.url}/login`);
  await page.waitForSelector('#skip:not([hidden])');
  assert.equal(await page.$eval('#access-mode', (element) => element.textContent), '本机访问');
  assert.equal((await fetch(`${admin.url}/login-display.woff2`)).status, 200, 'login font loads before authentication');
  assert.equal((await fetch(`${admin.url}/fonts/fonts.css`, { redirect: 'manual' })).status, 302, 'other font routes remain protected');
  await page.evaluate(() => document.fonts.ready);
  for (const [width, height] of [[320, 740], [768, 1024], [1440, 900]]) {
    await page.setViewport({ width, height });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `login fits ${width}px`);
  }
  await page.screenshot({ path: path.join(output, 'login-desktop.png') });
  await page.setViewport({ width: 390, height: 844 });
  await page.click('#reset summary');
  await page.type('#new-password', 'browser-test-password');
  await page.type('#confirm-password', 'browser-test-password');
  await page.screenshot({ path: path.join(output, 'login-mobile-reset.png') });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await Promise.all([page.waitForNavigation(), page.click('#reset-form button')]);
  await page.click('[data-tab="settings"]');
  await page.waitForSelector('[data-access-status]');
  await page.waitForFunction(() => document.querySelector('[data-access-status]').textContent.includes('已设置密码'));
  await page.click('[data-allow-remote]');
  await page.click('[data-access-form] button');
  await page.waitForSelector('dialog[open]');
  assert.equal(await page.$eval('[data-confirm]', (button) => button.disabled), true);
  await page.click('[data-cancel]');
  assert.equal(await page.$('dialog[open]'), null);
  await page.waitForFunction(() => !document.querySelector('[data-allow-remote]').checked);
  assert.equal(await page.$eval('[data-allow-remote]', (input) => input.checked), false);
  await page.click('[data-allow-remote]');
  await page.click('[data-access-form] button');
  await page.waitForSelector('dialog[open]');
  const started = Date.now();
  await page.screenshot({ path: path.join(output, 'remote-risk-mobile.png') });
  await page.waitForSelector('[data-confirm]:not([disabled])');
  assert.ok(Date.now() - started >= 4800, 'real timer must not unlock early');
  await page.click('[data-confirm]');
  await page.waitForFunction(() => document.querySelector('[data-access-saved]').textContent.includes('已保存'));
  await page.setViewport({ width: 1440, height: 900 });
  await page.$eval('#admin-access-settings', (section) => section.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: path.join(output, 'access-desktop.png') });
  const context = await browser.createBrowserContext();
  const remote = await context.newPage();
  remote.on('pageerror', (error) => errors.push(error.message));
  await remote.setExtraHTTPHeaders({ 'X-Forwarded-For': '203.0.113.99' });
  await remote.goto(admin.url); assert.ok(remote.url().endsWith('/login'));
  await remote.waitForFunction(() => !document.querySelector('#password').disabled);
  assert.equal(await remote.$eval('#access-mode', (element) => element.textContent), '非本机访问');
  assert.equal(await remote.$eval('#skip', (button) => button.hidden), true);
  assert.equal(await remote.$eval('#reset', (section) => section.hidden), true);
  await remote.type('#password', 'browser-test-password');
  await Promise.all([remote.waitForNavigation(), remote.click('#login-form button[type="submit"]')]);
  await remote.click('[data-tab="settings"]');
  await remote.waitForFunction(() => document.querySelector('[data-password-help]')?.textContent.includes('验证旧密码'));
  assert.equal(await remote.$eval('[data-old-password-label]', (label) => label.hidden), false);
  await page.click('[data-allow-remote]');
  await page.click('[data-access-form] button');
  await page.waitForFunction(() => document.querySelector('[data-access-status]').textContent.includes('仅允许本机访问'));
  const denied = await remote.goto(admin.url); assert.equal(denied.status(), 403);
  assert.equal((await fetch(`http://127.0.0.1:${game.port}/healthz`)).status, 200, 'game server continues across console rebinds');
  await page.click('#admin-logout'); await page.waitForSelector('#skip');
  await Promise.all([page.waitForNavigation(), page.click('#skip')]);
  assert.ok(page.url().endsWith('/'));
  assert.deepEqual(errors, []);
});
