import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { startServer } from '../../server/index.js';
import { startAdmin } from '../../server/admin.js';
import { StubMatch } from '../../server/match/StubMatch.js';
import { CHROME, hasChrome } from '../e2e/client.mjs';
test('multiple legacy origins: first prompt, consent summaries, selected restore, undo, relocation and authenticated console', { skip: process.env.SP_E2E !== '1' || !hasChrome(), timeout: 180000 }, async t => {
  let server, oldServer, olderServer, browser, admin;
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-domain-browser-'));
  const configFile = path.resolve('local/personal-data.json');
  const previous = fs.existsSync(configFile) ? fs.readFileSync(configFile) : null;
  const out = path.resolve('.cache/domain-recovery'); fs.mkdirSync(out, { recursive: true });
  t.after(async () => {
    await browser?.close(); await admin?.close(); await olderServer?.close(); await oldServer?.close(); await server?.close();
    if (previous) fs.writeFileSync(configFile, previous); else fs.rmSync(configFile, { force: true });
    fs.rmSync(dir, { recursive: true, force: true });
  });
  server = await startServer({ port: 0, host: '127.0.0.1', quiet: true, MatchClass: StubMatch, recovery: false });
  oldServer = await startServer({ port: 0, host: '127.0.0.1', quiet: true, MatchClass: StubMatch, recovery: false });
  olderServer = await startServer({ port: 0, host: '127.0.0.1', quiet: true, MatchClass: StubMatch, recovery: false });
  const canonicalOrigin = new URL(server.url).origin, oldOrigin = new URL(oldServer.url).origin, olderOrigin = new URL(olderServer.url).origin;
  const config = { canonicalOrigin, sources: [{ origin: oldOrigin, label: '旧站一', mode: 'smart', enabled: true }, { origin: olderOrigin, label: '旧站二', mode: 'notice', enabled: true }] };
  fs.mkdirSync(path.dirname(configFile), { recursive: true }); fs.writeFileSync(configFile, JSON.stringify(config));
  browser = await (await import('puppeteer-core')).default.launch({ executablePath: CHROME, headless: true, args: ['--no-sandbox'] });
  const context = await browser.createBrowserContext(), page = await context.newPage(), errors = [];
  t.after(() => t.diagnostic(JSON.stringify(errors)));
  const watch = page => { page.setDefaultTimeout(20000); page.on('pageerror', e => errors.push(e.message)); }; watch(page);
  await page.setViewport({ width: 1280, height: 800 });
  const old = await context.newPage(); watch(old);
  await old.goto(oldOrigin + '/personal-data-bridge.html');
  await old.evaluate(() => { localStorage.setItem('sp.name','OldDoctor'); localStorage.setItem('sp.pref.localAccount','{"tag":"4321"}'); localStorage.setItem('sp.pref.lastEnteredAt','1700000000000'); localStorage.setItem('sp.pref.skins','{}'); });
  await old.goto(oldOrigin); await old.waitForSelector('.domain-bridge');
  assert.match(await old.$eval('.domain-bridge',e=>e.textContent), /OldDoctor/);
  assert.equal(await old.evaluate(()=>localStorage.getItem('sp.pref.lastEnteredAt')), '1700000000000');
  await old.screenshot({ path: path.join(out,'moving-desktop.png') }); await old.close();
  const click = async (page, label, selector = 'button') => {
    await page.waitForFunction((label,selector)=>[...document.querySelectorAll(selector)].some(e=>e.textContent.trim()===label&&!e.disabled),{},label,selector);
    const button = await page.evaluateHandle((label,selector)=>[...document.querySelectorAll(selector)].find(e=>e.textContent.trim()===label),label,selector);
    await button.asElement().click(); await button.dispose();
  };
  const secondSeed = await context.newPage(); watch(secondSeed);
  await secondSeed.goto(olderOrigin+'/personal-data-bridge.html');
  await secondSeed.evaluate(()=>{localStorage.setItem('sp.name','OtherDoctor');localStorage.setItem('sp.pref.localAccount','{"tag":"9876"}');}); await secondSeed.close();
  const blockAutomatic = await page.evaluateOnNewDocument(()=>{ window.__savedOpen=window.open; window.open=()=>null; });
  await page.goto(canonicalOrigin); await page.waitForSelector('.recovery-panel');
  await page.waitForFunction(()=>document.querySelector('[data-testid=discovery-status]')?.textContent.includes('阻止'));
  await page.removeScriptToEvaluateOnNewDocument(blockAutomatic.identifier);
  await page.evaluate(()=>{window.open=window.__savedOpen;});
  assert.equal(await page.$$('.recovery-source').then(r=>r.length),2);
  await page.evaluate(()=>{ localStorage.setItem('sp.name','Before'); localStorage.setItem('sp.pref.settings','{"music":0}'); });
  const popupPromise = new Promise(resolve=>page.once('popup',resolve));
  let helperCount=0; page.on('popup',()=>helperCount++);
  await click(page,'查找全部旧站');
  const popup = await popupPromise; watch(popup);
  await page.waitForFunction(()=>document.querySelectorAll('.recovery-source .recovery-summary').length===2);
  await page.waitForFunction(()=>document.querySelector('[data-testid=discovery-status]')?.textContent.includes('已汇总'));
  assert.equal(helperCount,1,'one helper window collects every old-site response');
  assert.equal(await popup.$('#bridge-root button'),null,'configured sites respond without a second consent click');
  assert.match(await page.$eval('.recovery-source:nth-of-type(2)',e=>e.textContent),/OtherDoctor/);
  assert.match(await page.$eval('.recovery-source:first-of-type',e=>e.textContent),/OldDoctor/);
  assert.equal(await page.evaluate(()=>[...document.querySelectorAll('.recovery-panel button')].some(e=>e.textContent.includes('打开旧站检查'))),false);
  await page.screenshot({path:path.join(out,'auto-all-summaries-desktop.png')});
  await page.setViewport({width:844,height:390});
  assert.equal(await page.$eval('.personal-data-modal',e=>e.scrollWidth<=e.clientWidth+1),true);
  await page.screenshot({path:path.join(out,'auto-all-summaries-mobile.png')});
  await page.setViewport({width:1280,height:800});
  assert.equal(await page.evaluate(()=>localStorage.getItem('sp.name')),'Before','both candidates can be compared without writing');
  await click(page,'选择此存档'); await page.waitForSelector('[data-testid=recovery-preview]');
  assert.equal(helperCount,1,'selection reuses the helper and needs no additional popup or check click');
  assert.equal(await popup.evaluate(()=>localStorage.getItem('sp.pref.lastEnteredAt')), '1700000000000');
  assert.equal(await page.evaluate(()=>localStorage.getItem('sp.name')),'Before','preview never writes');
  await page.screenshot({ path: path.join(out,'recovery-desktop.png') });
  await page.setViewport({ width:844,height:390 }); await page.screenshot({ path:path.join(out,'recovery-mobile.png') });
  assert.equal(await page.$eval('.personal-data-modal',e=>e.scrollWidth<=e.clientWidth+1),true);
  await click(page,'确认并恢复'); await page.waitForFunction(()=>localStorage.getItem('sp.name')==='OldDoctor');
  assert.equal(await page.evaluate(()=>localStorage.getItem('sp.pref.skins')),'{}');
  await click(page,'撤销最近一次恢复'); await page.waitForNavigation({ waitUntil:'domcontentloaded' }).catch(()=>{});
  await page.waitForFunction(()=>!!globalThis.__SP__);
  assert.equal(await page.evaluate(()=>localStorage.getItem('sp.name')),'Before');
  assert.equal(await page.evaluate(()=>localStorage.getItem('sp.pref.skins')),null);
  if (await page.$('.recovery-panel')) await click(page,'关闭');
  await page.reload(); await page.waitForFunction(()=>!!globalThis.__SP__);
  assert.equal(await page.$('.recovery-panel'),null,'skipped prompt does not repeat');
  await click(page,'找回数据'); await page.waitForSelector('.recovery-panel');
  await page.waitForFunction(()=>document.querySelectorAll('.recovery-source .recovery-summary').length===2);
  assert.equal(await page.$eval('[data-testid=discovery-status]',e=>e.textContent.includes('已汇总')),true,'opening Find Data directly starts the whole scan without another button');
  await click(page,'关闭');
  // Old -> new takes one source click and lands directly at the restore preview.
  const directContext = await browser.createBrowserContext(), directOld = await directContext.newPage(); watch(directOld);
  await directOld.goto(oldOrigin+'/personal-data-bridge.html');
  await directOld.evaluate(()=>{localStorage.setItem('sp.name','DirectDoctor');localStorage.setItem('sp.pref.lastEnteredAt','1700000001234');localStorage.setItem('sp.pref.localAccount','{"tag":"2468"}');});
  await directOld.goto(oldOrigin); await directOld.waitForSelector('.domain-bridge');
  await directOld.evaluate(()=>{window.__savedOpen=window.open;window.open=()=>null;});
  await click(directOld,'迁移存档并前往新站');
  await directOld.waitForFunction(()=>document.querySelector('[role=alert]')?.textContent.includes('拦截'));
  await directOld.evaluate(()=>{window.open=window.__savedOpen;});
  const directPopupPromise = new Promise(resolve=>directOld.once('popup',resolve));
  await click(directOld,'迁移存档并前往新站');
  const directNew = await directPopupPromise; watch(directNew);
  try { await directNew.waitForSelector('[data-testid=recovery-preview]'); }
  catch (error) {
    t.diagnostic(JSON.stringify({new:await directNew.evaluate(()=>({url:location.href,opener:!!window.opener,body:document.body.innerText.slice(-3000)})),old:await directOld.evaluate(()=>({body:document.body.innerText.slice(-1500)}))}));
    throw error;
  }
  assert.match(await directNew.$eval('[data-testid=recovery-preview]',e=>e.textContent),/DirectDoctor/);
  assert.equal(await directNew.$('.recovery-source'),null,'direct handoff skips old-site check and candidate selection');
  assert.equal(await directNew.evaluate(()=>localStorage.getItem('sp.name')),null,'direct handoff still waits for restore confirmation');
  assert.equal(new URL(directNew.url()).hash,'','routing nonce removed after binding');
  await directOld.waitForFunction(()=>document.querySelector('[role=status]')?.textContent.includes('已送达'));
  await directNew.screenshot({path:path.join(out,'direct-transfer-preview.png')});
  await click(directNew,'确认并恢复'); await directNew.waitForFunction(()=>localStorage.getItem('sp.name')==='DirectDoctor');
  assert.equal(await directOld.evaluate(()=>localStorage.getItem('sp.name')),'DirectDoctor');
  assert.equal(await directOld.evaluate(()=>localStorage.getItem('sp.pref.lastEnteredAt')),'1700000001234');
  await directContext.close();
  const empty = await context.newPage(); watch(empty); await empty.goto(olderOrigin + '/personal-data-bridge.html');
  await empty.evaluate(()=>localStorage.clear()); await empty.reload();
  assert.match(await empty.$eval('#bridge-root',e=>e.textContent),/没有个人存档/);
  config.sources[1].mode='redirect'; fs.writeFileSync(configFile,JSON.stringify(config));
  await empty.goto(olderOrigin); await empty.waitForFunction(origin=>location.origin===origin,{},canonicalOrigin);
  await empty.goto(olderOrigin+'/personal-data-bridge.html'); assert.equal(new URL(empty.url()).origin,olderOrigin,'bridge survives redirect mode');
  const cleanContext = await browser.createBrowserContext(), clean = await cleanContext.newPage(); watch(clean);
  await clean.goto(oldOrigin); await clean.waitForFunction(origin=>location.origin===origin,{},canonicalOrigin); await cleanContext.close();
  admin = await startAdmin({ lobby: server.lobby, network: server.network, port:0, root:path.resolve('.'), resultsDir:path.join(dir,'results'), settingsFile:path.join(dir,'settings.json'), updateOptions:{fetchImpl:async()=>new Response('[]')},log:{info(){},error(){}} });
  const consolePage = await browser.newPage(); watch(consolePage); await consolePage.setViewport({width:1440,height:1000}); await consolePage.goto(admin.url);
  await consolePage.click('[data-tab=settings]'); await consolePage.waitForSelector('#domain-canonical');
  try { await consolePage.waitForFunction(origin=>document.querySelector('#domain-canonical')?.value===origin,{},canonicalOrigin); }
  catch (error) { t.diagnostic(JSON.stringify(await consolePage.evaluate(()=>({ text:document.querySelector('#domain-recovery-settings')?.innerText, body:document.body.innerText.slice(-600) })))); throw error; }
  await consolePage.$eval('#domain-recovery-settings',e=>e.scrollIntoView());
  await consolePage.screenshot({path:path.join(out,'console-domain-settings.png')});
  await consolePage.$eval('[data-domain-label]',e=>{e.value='已编辑旧站';e.dispatchEvent(new Event('input',{bubbles:true}));});
  await consolePage.click('[data-domain-save]'); await consolePage.waitForFunction(()=>document.querySelector('#domain-feedback').textContent.includes('已保存'));
  assert.equal(JSON.parse(fs.readFileSync(configFile,'utf8')).sources[0].label,'已编辑旧站');
  await consolePage.setViewport({width:390,height:844});
  await consolePage.$eval('#domain-recovery-settings',e=>e.scrollIntoView({block:'start'}));
  assert.equal(await consolePage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await consolePage.screenshot({path:path.join(out,'console-domain-mobile.png')});
  await consolePage.$eval('#domain-canonical',e=>{e.value='javascript:bad';});
  await consolePage.click('[data-domain-save]'); await consolePage.waitForFunction(()=>document.querySelector('#domain-feedback').textContent.includes('保存失败'));
  assert.equal(JSON.parse(fs.readFileSync(configFile,'utf8')).canonicalOrigin,canonicalOrigin);
  assert.equal(await consolePage.$eval('#domain-canonical',e=>e.value),'javascript:bad','failed save keeps draft');
  await consolePage.click('[data-domain-reset]');
  assert.equal(await consolePage.$eval('#domain-canonical',e=>e.value),canonicalOrigin);
  assert.deepEqual(errors,[]); t.diagnostic('All old-site responses collected through one helper with no per-site check/consent; selection, direct transfer, preview, restore, undo, popup blocking, redirects and console persistence verified.');
});
