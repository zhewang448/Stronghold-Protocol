import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { startAdmin } from '../../server/admin.js';
import { makeMatch } from '../match/harness.js';
import { CHROME, hasChrome } from '../e2e/client.mjs';
test('console overview, drawers, tabs, paging and notice presets', { skip: process.env.SP_E2E !== '1' || !hasChrome(), timeout: 60000 }, async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sp-overview-'));
  const h = makeMatch({ humans: 2, fake: true }).start().toPrep();
  const room = { code:'TEST',mode:'coop',difficulty:'NORMAL',seats:[],spectators:[],match:h.m };
  for (let i=0;i<170;i++) fs.writeFileSync(path.join(dir,'20261016-TEST-'+i+'.json'), JSON.stringify({ savedAt:Date.now()+i,room:i===169?'FIND':'TEST',mode:'coop',difficulty:'NORMAL',history:[],result:{victory:false,roundsPassed:1,durationMs:1000,players:[{playerId:'p_0',name:'Doctor '+i}]}}));
  const admin = await startAdmin({ lobby:{rooms:new Map([['TEST',room]]),safeData:()=>h.m.data,onMatchEnd(){}},port:0,resultsDir:dir,settingsFile:path.join(dir,'settings.json'),studioUrl:'http://127.0.0.1:3000/studio/#key=fixture',updateOptions:{fetchImpl:async()=>new Response('[]')},log:{info(){},error(){}} });
  const browser = await(await import('puppeteer-core')).default.launch({executablePath:CHROME,headless:true,args:['--no-sandbox']});
  t.after(async()=>{await browser.close();await admin.close();h.m.dispose();fs.rmSync(dir,{recursive:true,force:true});});
  const page=await browser.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(admin.url,{waitUntil:'domcontentloaded'});await page.waitForSelector('[data-open-room]');
  assert.equal(await page.$('[data-room-prep-mode]'),null);
  assert.equal(await page.$eval('#site-announcement',e=>e.getBoundingClientRect().height),0);
  await page.waitForFunction(()=>document.querySelector('#host-overview').textContent.includes('CPU'));
  await page.click('[data-open-room]');await page.waitForSelector('.player-summary');
  assert.equal(await page.$('.player-summary input'),null);
  assert.equal(await page.$('[data-act="lp"]'),null);
  await page.click('[data-toggle]');await page.waitForSelector('[data-act="lp"]');
  assert.deepEqual(await page.$$eval('.action-groups legend',es=>es.map(e=>e.textContent)),['数值','发放','托管']);
  await page.focus('[data-act="lp"]');const before=await page.$eval('[data-act="lp"]',e=>e.value);
  await page.hover('[data-act="lp"]');await page.mouse.wheel({deltaY:100});
  assert.equal(await page.$eval('[data-act="lp"]',e=>e.value),before);
  await page.click('[data-room-tab="data"]');await page.waitForSelector('[data-part="chart"]');
  assert.equal(await page.$eval('[data-room-prep]',e=>e.getBoundingClientRect().height),0);
  fs.mkdirSync('.cache/console-ui',{recursive:true});
  await page.screenshot({path:'.cache/console-ui/admin-data-desktop.png',fullPage:true});
  await page.click('[data-tab="records"]');await page.waitForSelector('#records-list tbody tr');
  assert.equal(await page.$$eval('#records-list tbody tr',es=>es.length),20);
  assert.match(await page.$eval('#record-pagination',e=>e.textContent),/170 条/);
  await page.click('[data-record-page="1"]');assert.match(await page.$eval('#record-pagination',e=>e.textContent),/第 2/);
  await page.type('#record-filter','FIND');assert.equal(await page.$$eval('#records-list tbody tr',es=>es.length),1);
  await page.click('[data-tab="settings"]');await page.waitForSelector('a[href="/studio"]');
  const issueLink = await page.$eval('#issue-feedback a', e => ({ href: e.href, target: e.target, rel: e.rel }));
  assert.deepEqual(issueLink, { href: 'https://github.com/zhewang448/Stronghold-Protocol/issues', target: '_blank', rel: 'noopener noreferrer' });
  assert.match(await page.$eval('#issue-feedback', e => e.textContent), /欢迎反馈使用中遇到的问题.*功能拓展建议/);
  const redirect = await fetch(admin.url + '/studio', { redirect: 'manual', headers: { Cookie: 'sp_admin=' + admin.token } });
  assert.equal(redirect.status, 302);
  assert.equal(redirect.headers.get('location'), 'http://127.0.0.1:3000/studio/#key=fixture');
  assert.equal((await fetch(admin.url + '/studio', { redirect: 'manual' })).status, 404);
  await page.click('[data-tab="server"]');assert.equal(await page.$eval('#site-notice-duration',e=>e.value),'3600000');
  await page.select('#site-notice-duration','untilRemoved');
  for(const [width,height] of [[1440,900],[720,700],[390,844]]){
    await page.setViewport({width,height});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:'.cache/console-ui/admin-server-'+width+'.png',fullPage:true});
  }
  assert.deepEqual(errors,[]);
});
