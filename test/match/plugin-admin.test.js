import { test } from 'node:test';
import assert from 'node:assert/strict';
import { fixture, bondPatch } from '../helpers/contentFixtures.js';
import { getData } from '../../server/data.js';
import { createContentSets } from '../../server/plugins/contentSets.js';
import { createMatchHosts } from '../../server/match/host/index.js';
import { roomsView, catalogView, handleAction } from '../../server/admin.js';
import { liveState, liveIntent } from '../../server/admin-live.js';
import { getReplayConfig, setReplayConfig } from '../../server/match/replay.js';
import { wallView } from '../../server/admin-wall.js';
import { setRoundCharts, resetHostSettings } from '../../server/match/hostSettings.js';
const quiet = { info() {}, warn() {}, error() {}, debug() {} };
for (const transport of ['process', 'worker']) test(`local console preserves gameplay-plugin administration through ${transport}`, { timeout: 30000 }, async t => {
  const savedReplay = getReplayConfig();
  setReplayConfig({ enabled: true, identity: 'plugin-admin-test' });
  t.after(() => setReplayConfig(savedReplay));
  setRoundCharts(false);
  t.after(() => resetHostSettings());
  const f = fixture(t);
  f.put('admin-probe', { data: ['patch.json'] }, { 'patch.json': bondPatch(0.35) });
  const contents = createContentSets({ registry: f.registry, vanillaData: getData({ log: quiet }), log: quiet });
  const resolved = contents.resolve(['admin-probe']);
  assert.ok(resolved.ok, JSON.stringify(resolved));
  contents.hold(resolved.set.cs);
  const hosts = createMatchHosts({ contents, log: quiet, options: { transport, matchOptions: { botRehearsal: 0 } } });
  t.after(() => hosts.close());
  const seats = [{ seat: 0, playerId: 'p_0', name: '主机', isBot: false, connected: true }];
  const m = hosts.create(resolved.set.cs, { roomCode: 'TEST', mode: 'coop', difficulty: 'NORMAL', seats, spectators: [], seed: 17, matchNo: 1, cs: resolved.set.cs, requireCs: true,
    send() { return true; }, broadcast() {}, onEnd() {} });
  m.start();
  const room = { code: 'TEST', mode: 'coop', seats, spectators: [], match: m };
  const lobby = { rooms: new Map([['TEST', room]]) };
  let view = (await roomsView(lobby))[0].match;
  assert.equal(view.players[0].name, '主机');
  const funds = view.players[0].funds;
  assert.deepEqual(await handleAction(lobby, { room: 'TEST', action: 'funds', playerId: 'p_0', value: 23 }), { ok: true });
  view = (await roomsView(lobby))[0].match;
  assert.equal(view.players[0].funds, funds + 23);
  assert.ok(room.adminLog.some(e => e.action === 'funds' && e.ok));
  assert.ok((await catalogView(lobby, 'TEST')).chess.length > 0);
  assert.equal((await wallView(lobby, 'TEST')).seats[0].funds, funds + 23);
  seats[0].connected = false;
  m.onDisconnect('p_0');
  assert.equal((await wallView(lobby, 'TEST')).seats[0].connected, false);
  assert.equal((await m.admin('wall')).seats[0].connected, false, 'child refreshes its own cached room seats');
  seats[0].connected = true;
  m.onReconnect('p_0');
  assert.equal((await wallView(lobby, 'TEST')).seats[0].connected, true);
  assert.equal((await m.admin('wall')).seats[0].connected, true);
  const live = await liveState(lobby, { room: 'TEST', playerId: 'p_0' });
  assert.equal(live.ok, true);
  assert.equal(live.room, 'TEST');
  assert.equal(live.controllable, true);
  assert.equal(live.public.roundCharts, false, 'initial host chart setting reaches the isolated match');
  assert.deepEqual(live.public.roundHistory, []);
  setRoundCharts(true);
  m.syncExtensions();
  assert.equal((await liveState(lobby, { room: 'TEST', playerId: 'p_0' })).public.roundCharts, true, 'live host changes reach isolated matches');
  assert.deepEqual(await liveIntent(lobby, { room: 'TEST', playerId: 'p_0', matchId: 'stale', intent: { t: 'g.infoReady' } }), { error: '玩家状态或回合已变化，请等待画面刷新后重试', code: 'BAD_TARGET' });
  assert.deepEqual(await m.setSkins('p_0', {}), { ok: true });
  assert.deepEqual(await m.setBondPlan('p_0', null), { ok: true });
  assert.equal((await handleAction(lobby, { room: 'TEST', action: 'rewind', value: 99 })).error.includes('快照'), true);
  assert.deepEqual(await handleAction(lobby, { room: 'TEST', action: 'endMatch' }), { ok: true });
  assert.equal(m.ended, true);
  assert.equal(m.extensionEnd.record.result.players[0].playerId, 'p_0');
  assert.equal(m.extensionEnd.replay.made.identity, 'plugin-admin-test');
  m.dispose();
});
